const SPACE_COLS = 3
const GAP_COLS = 1
export const PIXEL_FONT_ROWS = 8

type Glyph = { cols: number[][]; width: number }

const glyphs = new Map<string, Glyph>()
for (const [ch, rows] of Object.entries(G)) {
  const w = rows[0]!.length
  const lit = Array.from({ length: w }, (_, x) => rows.some(r => r[x] === '#'))
  const first = lit.indexOf(true), last = lit.lastIndexOf(true)
  const cols: number[][] = []
  for (let x = first; x <= last; x++) cols.push(rows.flatMap((r, y) => (r[x] === '#' ? [y] : [])))
  glyphs.set(ch, { cols, width: last - first + 1 })
}

export const PIXEL_FONT_CHARS = [...glyphs.keys()].join('') + ' '

/** Width in pixels of `text` at `scale`. Unknown characters count as spaces. */
export function pixelTextWidth(text: string, scale = 2): number {
  let cols = 0
  for (const ch of text.toLowerCase()) cols += (glyphs.get(ch)?.width ?? SPACE_COLS) + GAP_COLS
  return Math.max(0, cols - GAP_COLS) * scale
}

/** Draw `text` (lowercased) into a new grid, 8 x `scale` pixels tall. */
export function pixelText(text: string, opts: { scale?: number; level?: number } = {}): Grid {
  const { scale = 2, level = 15 } = opts
  const out = grid(Math.max(1, pixelTextWidth(text, scale)), PIXEL_FONT_ROWS * scale)
  let x = 0
  for (const ch of text.toLowerCase()) {
    const g = glyphs.get(ch)
    if (g) g.cols.forEach((ys, i) => ys.forEach(y => fillRect(out, (x + i) * scale, y * scale, scale, scale, level)))
    x += (g?.width ?? SPACE_COLS) + GAP_COLS
  }
  return out
}
